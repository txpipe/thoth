// `thoth generate` and `thoth compile --skip-zk` in a temp project, then the zkFetch dev
// witnesses -> attestors -> generated client and witnesses -> the compiled app contract.
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import {
  createCircuitContext,
  createConstructorContext,
  dummyContractAddress,
} from '@midnight-ntwrk/compact-runtime';
import { holderCommitmentOf } from '@thoth/core/claim-context';
import { zkTls } from '@thoth/zk-tls/thoth';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { devKeyPair } from './fixtures/app/keys.js';
import { makeProject, type Project } from './helpers/project.js';

const COIN_PK = '0'.repeat(64);
const OBSERVED_AT = Math.floor(Date.now() / 1000) - 30;

const padded32 = (value: string): Uint8Array => {
  const out = new Uint8Array(32);
  out.set(new TextEncoder().encode(value));
  return out;
};

// biome-ignore lint/suspicious/noExplicitAny: the compiled contract is imported at run time.
type Module = any;

describe('thoth generate, compile and the simulator', () => {
  let project: Project;
  let generated: Module;
  let compiled: Module;
  let contract: Module;
  let state: Module;
  let privateState: Module;
  let claimId: Uint8Array;
  let attestment: Module;

  const call = async (circuit: string, ...args: unknown[]) => {
    const context = createCircuitContext({
      circuitId: circuit,
      contractAddress: dummyContractAddress(),
      coinPublicKeyOrZswapState: COIN_PK,
      contractState: state,
      privateState,
      time: OBSERVED_AT + 60,
    });
    const result = await contract.circuits[circuit](context, ...args);
    state = result.context.callContext.currentQueryContext.state;
    return result.result;
  };

  beforeAll(async () => {
    project = makeProject();
    const generate = project.thoth('generate');
    expect(generate.stderr).toBe('');
    expect(generate.status).toBe(0);
    const compile = project.thoth('compile', '--skip-zk');
    expect(compile.status, compile.stderr).toBe(0);

    generated = await import(project.path('src/generated/thoth.ts'));
    compiled = await import(project.path('artifacts/app/contract/index.js'));

    const policy = zkTls.policySchema.parse(generated.POLICY);
    const devEvidence = zkTls.devEvidence;
    if (devEvidence === undefined) throw new Error('zkTls has no devEvidence');
    const operators = devEvidence(policy, 3, {
      values: { distance: '5012', athlete: 'alice' },
      timestampS: OBSERVED_AT,
    });
    const attestors = operators.map(({ attestorConfig }, i) =>
      zkTls.attestor({ id: `dev-${i}`, keyPair: devKeyPair(i), ...attestorConfig }),
    );
    const client = generated.createClient({
      transport: {
        request: (descriptor: { id: string }, input: unknown) => {
          const attestor = attestors.find((candidate) => candidate.id === descriptor.id);
          if (attestor === undefined) throw new Error(`unknown attestor ${descriptor.id}`);
          return attestor.attest(input as Parameters<typeof attestor.attest>[0]);
        },
      },
      provers: Object.fromEntries(operators.map(({ prover }, i) => [`dev-${i}`, prover])),
    });

    const holderSecret = randomBytes(32);
    const commitRand = randomBytes(32);
    // Ask registry slots 2 and 0 only, in that order: placement must follow the slot.
    attestment = await client.collect(
      { url: 'https://www.strava.com/api/v3/activities/1', method: 'GET' },
      {
        holder: holderCommitmentOf(holderSecret),
        windowStart: BigInt(OBSERVED_AT),
        windowEnd: BigInt(OBSERVED_AT + 60),
        expiresAt: Date.now() + 60_000,
        threshold: 2,
        attestorTimeoutMs: 10_000,
        attestorIds: ['dev-2', 'dev-0'],
      },
    );
    privateState = generated.privateStateOf(attestment, holderSecret, commitRand);
    claimId = compiled.pureCircuits.claimId(privateState.claim, commitRand);
    contract = new compiled.Contract(generated.witnesses);
    const deploy = await contract.initialState(createConstructorContext(privateState, COIN_PK));
    state = deploy.currentContractState.data;
  }, 180_000);

  afterAll(() => project?.remove());

  it('marks every generated file as generated', () => {
    for (const file of [
      'contract/generated/thoth.compact',
      'src/generated/thoth.ts',
      'src/generated/thoth.check.ts',
    ]) {
      expect(project.read(file)).toMatch(/^\/\/ Generated by `thoth generate`/);
    }
  });

  it('type-checks the generated TypeScript in strict mode', () => {
    const check = project.typeCheck();
    expect(check.stdout).toBe('');
    expect(check.status).toBe(0);
  }, 60_000);

  it('derives the module parameters from the config', () => {
    expect(project.read('contract/generated/thoth.compact')).toContain(
      'import "attestation"<22, 2, 2, 2, 3> prefix Thoth_;',
    );
    expect(generated.LAYOUT).toEqual({
      valueSlots: 2,
      byteSlots: 1,
      byteHalves: 2,
      messageFields: 22,
      threshold: 2,
      registrySize: 3,
    });
  });

  it('seals the app id, the policy hash and the attestor keys in registry slot order', () => {
    const ledger = compiled.ledger(state);
    expect(ledger.Thoth_appId).toEqual(new Uint8Array(32).fill(0xa1));
    expect(ledger.Thoth_freshnessWindow).toBe(86400n);
    expect(ledger.Thoth_maxWindow).toBe(300n);
    expect(ledger.Thoth_policyHashes.member(zkTls.policyHashOf(generated.POLICY))).toBe(true);
    expect(generated.ATTESTORS.map((a: { id: string }) => a.id)).toEqual([
      'dev-0',
      'dev-1',
      'dev-2',
    ]);
  });

  it('places each signature at its registry slot', () => {
    expect(privateState.signatures).toHaveLength(3);
    expect(privateState.signatures[1].response).toBe(0n);
    expect(privateState.signatures[0].response).not.toBe(0n);
    expect(privateState.signatures[2].response).not.toBe(0n);
  });

  it('accepts the 2-of-3 claim', async () => {
    await call('verifyAttestation');
    expect(compiled.ledger(state).Thoth_claimsVault.member(claimId)).toBe(true);
  });

  it('runs the predicate through the named accessors', async () => {
    await call('claimReward', claimId, 5000n, padded32('alice'));
    expect(compiled.ledger(state).rewarded).toBe(1n);
  });

  it('rejects through the named accessors', async () => {
    await expect(call('claimReward', claimId, 6000n, padded32('alice'))).rejects.toThrow(
      'Run too short',
    );
    await expect(call('claimReward', claimId, 5000n, padded32('bob'))).rejects.toThrow(
      'Wrong athlete',
    );
  });

  it('reads an absent optional slot through its presence flag', async () => {
    expect(privateState.claim.present).toEqual([true, false]);
    await call('movedLongEnough', claimId, 999n);
  });

  it('fails the accessor assert when a predicate reads an absent slot without its flag', async () => {
    await expect(call('movingTimeAtLeast', claimId, 1n)).rejects.toThrow('movingTime not measured');
  });

  it.each([
    ['a registry slot answered twice', [0, 0], 'registry slot 0 is answered twice'],
    ['a registry slot outside the registry', [0, 3], 'registry slot 3 is outside 0..2'],
  ])('refuses to place signatures with %s', (_, slots, message) => {
    const [first, second] = attestment.collected;
    const collected = [
      { ...first, registryIndex: slots[0] },
      { ...second, registryIndex: slots[1] },
    ];
    expect(() =>
      generated.privateStateOf({ ...attestment, collected }, randomBytes(32), randomBytes(32)),
    ).toThrow(message);
  });

  it('refuses a claim for another policy', () => {
    const claim = { ...attestment.claim, policyHash: new Uint8Array(32) };
    expect(() =>
      generated.privateStateOf({ ...attestment, claim }, randomBytes(32), randomBytes(32)),
    ).toThrow('the claim is for another policy');
  });

  it('loads the config check under plain Node', () => {
    const run = spawnSync(
      process.execPath,
      [
        '--input-type=module',
        '-e',
        `await import(${JSON.stringify(project.path('src/generated/thoth.check.ts'))})`,
      ],
      { cwd: project.dir, encoding: 'utf8' },
    );
    expect(run.status, run.stderr).toBe(0);
  });

  it('loads the config check while the config is unchanged', async () => {
    const check = await import(project.path('src/generated/thoth.check.ts'));
    expect(check.config.threshold).toBe(2);
  });
});
